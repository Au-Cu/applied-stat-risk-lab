def choose_hub(school: str, location: str) -> str:
    if school in SCHOOL_HUB_OVERRIDES:
        return SCHOOL_HUB_OVERRIDES[school]
    for needle, hub in LOCATION_RULES:
        if needle in location:
            return hub
    raise ValueError(f"No office hub for {school}: {location}")


def route_url(school: dict, hub_name: str, hub_lat: float, hub_lng: float) -> str:
    params = urllib.parse.urlencode(
        {
            "from": f"{school['longitude']},{school['latitude']},{school['school']}",
            "to": f"{hub_lng},{hub_lat},{hub_name}",
            "mode": "bus",
            "policy": "0",
            "src": "applied-stat-risk-lab",
            "callnative": "0",
        }
    )
    return f"https://uri.amap.com/navigation?{params}"


def main() -> None:
    with SCHOOLS.open(encoding="utf-8-sig", newline="") as handle:
        schools = list(csv.DictReader(handle))
    rows = []
    for school in schools:
        hub_key = choose_hub(school["school"], school.get("location", ""))
        hub_name, hub_lat, hub_lng = HUBS[hub_key]
        mode, lines, summary = TRANSIT[school["school"]]
        rows.append(
            {
                "school": school["school"],
                "office_hub": hub_name,
                "office_hub_latitude": hub_lat,
                "office_hub_longitude": hub_lng,
                "office_hub_definition": "代表性公司办公集聚节点；不等同于就业机会排名",
                "office_hub_review_status": "研究用节点，待人工复核",
                "transit_mode": mode,
                "transit_lines": lines,
                "transit_summary": summary,
                "transit_review_status": "候选线路，待按报名年份逐段复核",
                "live_route_url": route_url(school, hub_name, hub_lat, hub_lng),
                "route_source": "高德地图URI API实时公交规划",
            }
        )
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    print(f"Wrote {len(rows)} rows to {OUTPUT}")


if __name__ == "__main__":
    main()
